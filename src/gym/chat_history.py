from langchain_core.messages import AIMessage, HumanMessage

from .database import get_oracle_connection


def _ensure_history_table(cursor) -> None:
    cursor.execute(
        "SELECT COUNT(*) FROM user_tables WHERE UPPER(table_name) = :table_name",
        {"table_name": "HISTORIAL_CHAT"},
    )
    if cursor.fetchone()[0] == 0:
        cursor.execute("""
            CREATE TABLE historial_chat (
                id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                usuario_id NUMBER NOT NULL,
                rol VARCHAR2(20) NOT NULL,
                contenido CLOB NOT NULL,
                fecha_creacion DATE DEFAULT SYSDATE,
                CONSTRAINT fk_histchat_usuario
                    FOREIGN KEY (usuario_id) REFERENCES usuarios(id),
                CONSTRAINT ck_histchat_rol CHECK (rol IN ('human', 'ai'))
            )
        """)


def guardar_intercambio_chat(usuario_id: int, pregunta: str, respuesta: str) -> dict:
    if usuario_id is None:
        return {"ok": False, "error": "La sesión no tiene un usuario válido."}

    conn = None
    try:
        conn = get_oracle_connection()
        cursor = conn.cursor()
        _ensure_history_table(cursor)
        for rol, contenido in (("human", pregunta), ("ai", respuesta)):
            cursor.execute(
                "INSERT INTO historial_chat (usuario_id, rol, contenido) "
                "VALUES (:usuario_id, :rol, :contenido)",
                {"usuario_id": usuario_id, "rol": rol, "contenido": contenido},
            )
        conn.commit()
        return {"ok": True}
    except Exception:
        if conn is not None:
            conn.rollback()
        return {"ok": False, "error": "No se pudo guardar la conversación en Oracle."}
    finally:
        if conn is not None:
            conn.close()


def cargar_historial_chat(usuario_id: int, limite: int = 40) -> dict:
    if usuario_id is None:
        return {"ok": False, "error": "La sesión no tiene un usuario válido."}

    conn = None
    try:
        conn = get_oracle_connection()
        cursor = conn.cursor()
        _ensure_history_table(cursor)
        cursor.execute(
            "SELECT id, rol, contenido FROM ("
            "SELECT id, rol, contenido FROM historial_chat "
            "WHERE usuario_id = :usuario_id ORDER BY id DESC"
            ") WHERE ROWNUM <= :limite ORDER BY id",
            {"usuario_id": usuario_id, "limite": max(1, min(int(limite), 200))},
        )

        mensajes = []
        for _, rol, contenido in cursor.fetchall():
            if hasattr(contenido, "read"):
                contenido = contenido.read()
            message_type = HumanMessage if rol == "human" else AIMessage
            mensajes.append(message_type(content=str(contenido)))
        return {"ok": True, "mensajes": mensajes}
    except Exception:
        return {"ok": False, "error": "No se pudo cargar la conversación desde Oracle."}
    finally:
        if conn is not None:
            conn.close()