import hashlib
import hmac
import os
import re
import secrets

from .database import get_oracle_connection

PASSWORD_ITERATIONS = 310_000
EMAIL_PATTERN = re.compile(r"^[^\s@]+@[^\s@]+\.[^\s@]+$")


def _hash_password(password: str) -> str:
    salt = secrets.token_bytes(16)
    password_hash = hashlib.pbkdf2_hmac(
        "sha256", password.encode("utf-8"), salt, PASSWORD_ITERATIONS
    )
    return f"pbkdf2_sha256${PASSWORD_ITERATIONS}${salt.hex()}${password_hash.hex()}"


def _verify_password(password: str, stored_hash: str) -> bool:
    try:
        algorithm, iterations, salt_hex, hash_hex = stored_hash.split("$", 3)
        if algorithm != "pbkdf2_sha256":
            return False
        candidate = hashlib.pbkdf2_hmac(
            "sha256", password.encode("utf-8"), bytes.fromhex(salt_hex), int(iterations)
        )
        return hmac.compare_digest(candidate, bytes.fromhex(hash_hex))
    except (TypeError, ValueError):
        return False


def _rol_para_correo(correo: str) -> str:
    administradores = {
        valor.strip().lower()
        for valor in os.getenv("GYM_ADMIN_EMAILS", "").split(",")
        if valor.strip()
    }
    return "ADMIN" if correo in administradores else "MIEMBRO"


def _ensure_users_table(cursor) -> None:
    cursor.execute(
        "SELECT COUNT(*) FROM user_tables WHERE UPPER(table_name) = :table_name",
        {"table_name": "USUARIOS"},
    )
    if cursor.fetchone()[0] == 0:
        cursor.execute("""
            CREATE TABLE usuarios (
                id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                nombre VARCHAR2(200) NOT NULL,
                correo VARCHAR2(320) NOT NULL UNIQUE,
                password_hash VARCHAR2(255) NOT NULL,
                rol VARCHAR2(20) DEFAULT 'MIEMBRO' NOT NULL,
                fecha_registro DATE DEFAULT SYSDATE
            )
        """)
    cursor.execute("""
        SELECT COUNT(*) FROM user_tab_columns
        WHERE table_name = 'USUARIOS' AND column_name = 'ROL'
    """)
    if cursor.fetchone()[0] == 0:
        cursor.execute(
            "ALTER TABLE usuarios ADD (rol VARCHAR2(20) DEFAULT 'MIEMBRO' NOT NULL)"
        )


def registrar_usuario(nombre: str, correo: str, password: str) -> dict:
    nombre_limpio = (nombre or "").strip()
    correo_limpio = (correo or "").strip().lower()

    if not nombre_limpio:
        return {"ok": False, "error": "Ingresa tu nombre."}
    if not EMAIL_PATTERN.fullmatch(correo_limpio):
        return {"ok": False, "error": "Ingresa un correo válido."}
    if len(password or "") < 8:
        return {"ok": False, "error": "La contraseña debe tener al menos 8 caracteres."}

    conn = None
    try:
        conn = get_oracle_connection()
        cursor = conn.cursor()
        _ensure_users_table(cursor)
        cursor.execute(
            "SELECT COUNT(*) FROM usuarios WHERE correo = :correo",
            {"correo": correo_limpio},
        )
        if cursor.fetchone()[0] > 0:
            return {"ok": False, "error": "Ya existe una cuenta con ese correo."}

        cursor.execute(
            "INSERT INTO usuarios (nombre, correo, password_hash, rol) "
            "VALUES (:nombre, :correo, :password_hash, :rol)",
            {
                "nombre": nombre_limpio,
                "correo": correo_limpio,
                "password_hash": _hash_password(password),
                "rol": _rol_para_correo(correo_limpio),
            },
        )
        cursor.execute(
            "SELECT id FROM usuarios WHERE correo = :correo",
            {"correo": correo_limpio},
        )
        usuario_id = cursor.fetchone()[0]
        conn.commit()
        return {
            "ok": True,
            "usuario": {
                "id": usuario_id,
                "nombre": nombre_limpio,
                "correo": correo_limpio,
                "rol": _rol_para_correo(correo_limpio),
            },
        }
    except Exception:
        if conn is not None:
            conn.rollback()
        return {"ok": False, "error": "No se pudo crear la cuenta. Revisa la conexión con Oracle."}
    finally:
        if conn is not None:
            conn.close()


def iniciar_sesion(correo: str, password: str) -> dict:
    correo_limpio = (correo or "").strip().lower()
    if not correo_limpio or not password:
        return {"ok": False, "error": "Ingresa tu correo y contraseña."}

    conn = None
    try:
        conn = get_oracle_connection()
        cursor = conn.cursor()
        _ensure_users_table(cursor)
        cursor.execute(
            "SELECT id, nombre, correo, password_hash, rol FROM usuarios WHERE correo = :correo",
            {"correo": correo_limpio},
        )
        usuario = cursor.fetchone()
        if not usuario or not _verify_password(password, usuario[3]):
            return {"ok": False, "error": "Correo o contraseña incorrectos."}
        rol = (usuario[4] or "MIEMBRO").upper()
        if _rol_para_correo(correo_limpio) == "ADMIN" and rol != "ADMIN":
            cursor.execute(
                "UPDATE usuarios SET rol = 'ADMIN' WHERE id = :usuario_id",
                {"usuario_id": usuario[0]},
            )
            conn.commit()
            rol = "ADMIN"
        return {
            "ok": True,
            "usuario": {
                "id": usuario[0],
                "nombre": usuario[1],
                "correo": usuario[2],
                "rol": rol,
            },
        }
    except Exception:
        return {"ok": False, "error": "No se pudo iniciar sesión. Revisa la conexión con Oracle."}
    finally:
        if conn is not None:
            conn.close()