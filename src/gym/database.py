        inscripcion_id = cursor.fetchone()[0]

        cursor.execute("INSERT INTO ventas (cliente_id, inscripcion_id, fecha_venta, total, metodo_pago, estado) VALUES (:cliente_id, :inscripcion_id, SYSDATE, :total, :metodo, 'PENDIENTE')", (cliente_id, inscripcion_id, monto_float, metodo_limpio))
