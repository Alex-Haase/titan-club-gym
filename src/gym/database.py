def obtener_precios_planes() -> dict[str, float]:
    conn = get_oracle_connection()
    try:
        cursor = conn.cursor()
        cursor.execute("""
            SELECT LOWER(nombre), precio_clp
            FROM planes
            WHERE activo = 1
        """)
        return {str(nombre).strip().lower(): float(precio) for nombre, precio in cursor.fetchall()}
    finally:
        conn.close()


def sincronizar_plan_actual_cliente(cursor, cliente_id: int) -> str | None:
    cursor.execute("""
        SELECT plan FROM (
            SELECT LOWER(p.nombre) AS plan,
                   ROW_NUMBER() OVER (ORDER BY i.fecha_inscripcion DESC, i.id DESC) AS rn
            FROM inscripciones i
            JOIN planes p ON p.id = i.plan_id
            JOIN clientes c ON c.id = i.cliente_id
            WHERE i.cliente_id = :cliente_id
              AND NVL(c.activo, 1) = 1
              AND UPPER(i.estado) IN ('ACTIVA', 'RENOVADA')
              AND TRUNC(i.fecha_inscripcion) <= TRUNC(SYSDATE)
              AND TRUNC(SYSDATE) <
                  TRUNC(i.fecha_inscripcion) + NVL(p.duracion_dias, 30)
        ) WHERE rn = 1
    """, {"cliente_id": cliente_id})
    fila = cursor.fetchone()
    if not fila:
        return None

    plan = str(fila[0]).strip().lower()
    cursor.execute("""
        UPDATE clientes SET plan_actual = :plan
        WHERE id = :cliente_id
          AND NVL(LOWER(plan_actual), ' ') <> :plan
    """, {"plan": plan, "cliente_id": cliente_id})
    return plan


def obtener_membresias_activas_por_plan() -> dict[str, int]:
    conn = get_oracle_connection()
    try:
        cursor = conn.cursor()
        cursor.execute("""
            SELECT COUNT(*) FROM user_tab_columns
            WHERE table_name = 'CLIENTES' AND column_name = 'ACTIVO'
        """)
        tiene_estado_cliente = cursor.fetchone()[0] > 0
        filtro_cliente = "AND NVL(c.activo, 1) = 1" if tiene_estado_cliente else ""
        cursor.execute(f"""
            SELECT plan, COUNT(*) FROM (
                SELECT LOWER(p.nombre) AS plan,
                       ROW_NUMBER() OVER (
                           PARTITION BY i.cliente_id ORDER BY i.id DESC
                       ) AS rn
                FROM inscripciones i
                JOIN planes p ON p.id = i.plan_id
                JOIN clientes c ON c.id = i.cliente_id
                WHERE UPPER(i.estado) IN ('ACTIVA', 'RENOVADA')
                  AND TRUNC(i.fecha_inscripcion) <= TRUNC(SYSDATE)
                  AND TRUNC(SYSDATE) <
                      TRUNC(i.fecha_inscripcion) + NVL(p.duracion_dias, 30)
                  {filtro_cliente}
            ) WHERE rn = 1
            GROUP BY plan
        """)
        return {str(plan).strip().lower(): int(cantidad) for plan, cantidad in cursor.fetchall()}
    finally:
        conn.close()


def obtener_plan_vigente_cliente(nombre: str) -> str | None:
    nombre_limpio = (nombre or "").strip()
    if not nombre_limpio:
        return None

    conn = get_oracle_connection()
    try:
        cursor = conn.cursor()
        cursor.execute("""
            SELECT COUNT(*) FROM user_tab_columns
            WHERE table_name = 'CLIENTES' AND column_name = 'ACTIVO'
        """)
        tiene_estado_cliente = cursor.fetchone()[0] > 0
        filtro_cliente = "AND NVL(c.activo, 1) = 1" if tiene_estado_cliente else ""
        cursor.execute(f"""
            SELECT plan FROM (
                SELECT LOWER(p.nombre) AS plan,
                       ROW_NUMBER() OVER (ORDER BY i.id DESC) AS rn
                FROM inscripciones i
                JOIN planes p ON p.id = i.plan_id
                JOIN clientes c ON c.id = i.cliente_id
                WHERE LOWER(c.nombre) = LOWER(:nombre)
                  AND UPPER(i.estado) IN ('ACTIVA', 'RENOVADA')
                  AND TRUNC(i.fecha_inscripcion) <= TRUNC(SYSDATE)
                  AND TRUNC(SYSDATE) <
                      TRUNC(i.fecha_inscripcion) + NVL(p.duracion_dias, 30)
                  {filtro_cliente}
            ) WHERE rn = 1
        """, {"nombre": nombre_limpio})
        fila = cursor.fetchone()
        return str(fila[0]).strip().lower() if fila else None
    finally:
        conn.close()
