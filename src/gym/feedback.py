import re

from .database import get_oracle_connection

EMAIL_PATTERN = re.compile(r"^[^\s@]+@[^\s@]+\.[^\s@]+$")
ESTADOS_SUGERENCIA = {"NUEVA", "REVISADA", "RESPONDIDA"}


def _asegurar_tabla_sugerencias(cursor) -> None:
    cursor.execute(
        "SELECT COUNT(*) FROM user_tables WHERE table_name = 'SUGERENCIAS'"
    )
    if cursor.fetchone()[0] == 0:
        cursor.execute("""
            CREATE TABLE sugerencias (
                id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                nombre VARCHAR2(200),
                correo VARCHAR2(320),
                mensaje VARCHAR2(1000) NOT NULL,
                estado VARCHAR2(20) DEFAULT 'NUEVA' NOT NULL,
                fecha_creacion DATE DEFAULT SYSDATE
            )
        """)


def enviar_sugerencia(nombre: str, correo: str, mensaje: str) -> dict:
    nombre_limpio = (nombre or "").strip()
    correo_limpio = (correo or "").strip().lower()
    mensaje_limpio = (mensaje or "").strip()
    if not mensaje_limpio:
        return {"ok": False, "error": "Escribe tu sugerencia antes de enviarla."}
    if len(mensaje_limpio) > 1000:
        return {"ok": False, "error": "La sugerencia no puede superar 1000 caracteres."}
    if correo_limpio and not EMAIL_PATTERN.fullmatch(correo_limpio):
        return {"ok": False, "error": "Revisa el formato del correo de contacto."}

    conn = None
    try:
        conn = get_oracle_connection()
        cursor = conn.cursor()
        _asegurar_tabla_sugerencias(cursor)
        cursor.execute("""
            INSERT INTO sugerencias (nombre, correo, mensaje, estado)
            VALUES (:nombre, :correo, :mensaje, 'NUEVA')
        """, {
            "nombre": nombre_limpio or None,
            "correo": correo_limpio or None,
            "mensaje": mensaje_limpio,
        })
        conn.commit()
        return {"ok": True}
    except Exception:
        if conn is not None:
            conn.rollback()
        return {"ok": False, "error": "No se pudo guardar la sugerencia. Inténtalo más tarde."}
    finally:
        if conn is not None:
            conn.close()


