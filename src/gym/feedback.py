def cambiar_estado_sugerencia_admin(sugerencia_id: int, estado: str) -> dict:
    estado_limpio = (estado or "").strip().upper()
    if estado_limpio not in ESTADOS_SUGERENCIA:
        return {"ok": False, "error": "Estado de sugerencia inválido."}

    conn = None
    try:
        conn = get_oracle_connection()
        cursor = conn.cursor()
        _asegurar_tabla_sugerencias(cursor)
        cursor.execute("""
            UPDATE sugerencias SET estado = :estado
            WHERE id = :sugerencia_id
        """, {"estado": estado_limpio, "sugerencia_id": sugerencia_id})
        conn.commit()
        return {"ok": True}
    except Exception:
        if conn is not None:
            conn.rollback()
        return {"ok": False, "error": "No se pudo actualizar la sugerencia."}
    finally:
        if conn is not None:
            conn.close()